export function getRecentlyUsed() {
  try {
    return JSON.parse(localStorage.getItem('nyxora-recent-emojis') || '[]')
  } catch {
    return []
  }
}

export function addRecentlyUsed(emoji) {
  try {
    let recent = getRecentlyUsed().filter(e => e !== emoji)
    recent.unshift(emoji)
    if (recent.length > 30) recent = recent.slice(0, 30)
    localStorage.setItem('nyxora-recent-emojis', JSON.stringify(recent))
  } catch {}
}
